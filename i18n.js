const escHTML = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

function t(key, vars = {}) {
  const str = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k];
    if (v == null) return "";
    return typeof v === "object" ? v.html : escHTML(v);
  });
}

const catName = (cat) => (LANG === "ar" ? CATEGORY_AR[cat] ?? cat : cat);
const wordText = (cat, idx) => (LANG === "ar" ? WORDS_AR[cat]?.[idx] : WORDS[cat]?.[idx]) ?? "";
const maskName = (i) => (LANG === "ar" ? MASK_NAMES_AR[i] : MASKS[i]?.name) ?? "";

function applyLang(lang) {
  LANG = lang in STRINGS ? lang : "en";
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
  document.title = t("docTitle");
}

// Loose comparison for words in either language: ignores case, accents, Arabic
// diacritics, alef/taa-marbuta/yaa variants and a leading "ال".
function normWord(s) {
  return String(s)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[̀-ًͯ-ٰٟـ]/g, "")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/(^|\s)ال/g, "$1")
    .replace(/[^\p{L}\p{N}]/gu, "");
}
